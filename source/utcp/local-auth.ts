import {
  chmodSync, closeSync, constants, existsSync, fsyncSync, lstatSync, openSync,
  readFileSync, renameSync, unlinkSync, writeSync,
} from "fs";
import { createHash, randomBytes, timingSafeEqual } from "crypto";
import type { IncomingMessage } from "http";
import { homedir } from "os";
import { dirname, join } from "path";
import { z } from "zod";
import { CcpError, CcpErrorBody, toCcpErrorBody } from "../protected/errors";
import { ensurePrivateDirectory } from "../protected/durable-file";
import { encodeBase64Url } from "../protected/node14-compat";
import { projectIdentity } from './project-connection';

export const LOCAL_TOKEN_HEADER = "x-ccp-local-token";
export const LOCAL_INSTANCE_HEADER = "x-ccp-relay-instance";
export const LOCAL_PORT_HEADER = "x-ccp-bound-port";
export const LOCAL_PROJECT_HEADER = "x-ccp-project-id";
export const IDEMPOTENCY_KEY_HEADER = "x-ccp-idempotency-key";
export const LOCAL_TOKEN_VARIABLE = "CCP_LOCAL_TOKEN";
export const LOCAL_INSTANCE_VARIABLE = "CCP_RELAY_INSTANCE_ID";
export const LOCAL_PORT_VARIABLE = "CCP_BOUND_PORT";
export const LOCAL_PROJECT_VARIABLE = "CCP_LOCAL_PROJECT_ID";
const MAX_TOKEN_FILE_BYTES = 4096;
const IdempotencyKeySchema = z.string().min(16).max(128).regex(/^[A-Za-z0-9_-]+$/);

export interface LocalAuthContext {
  relayInstanceId: string;
  token: string;
  tokenPath: string;
  variableName: string;
  boundPort?: number;
  projectId?: string;
  projectPath?: string;
}

export interface LocalAuthBinding {
  templateName: string;
  tokenPath: string;
  previousPort?: number;
}

export interface LocalIngressDenial {
  status: number;
  body: CcpErrorBody;
}
function effectiveVariableName(templateName: string, variableName: string): string {
  const namespace = templateName.replace(/_/g, "__");
  return `${namespace}_${variableName}`;
}

export function assertLocalAuthFile(auth: LocalAuthContext): void {
  const stat = lstatSync(auth.tokenPath);
  if (stat.isSymbolicLink() || !stat.isFile()) throw new Error("local auth token path must be a regular file");
  if (process.platform !== "win32" && (stat.mode & 0o077) !== 0) throw new Error("local auth token file must be user-private");
  if (stat.size < 1 || stat.size > MAX_TOKEN_FILE_BYTES) throw new RangeError("local auth token file exceeds the credential bound");
  const expected = tokenFileContent(auth, auth.boundPort);
  if (readFileSync(auth.tokenPath, 'utf8') !== expected) throw new Error('local auth file does not match the current project session');
}

function tokenFileContent(auth: LocalAuthContext, port?: number): string {
  if (!auth.projectId || !auth.projectPath || port === undefined) throw new Error('project credentials require an exact project and port');
  const templateName = `ccp3x_${port}`;
  return [
    "# Generated by CCP. Keep this file private.",
    `${effectiveVariableName(templateName, LOCAL_INSTANCE_VARIABLE)}=${auth.relayInstanceId}`,
    `${effectiveVariableName(templateName, LOCAL_TOKEN_VARIABLE)}=${auth.token}`,
    `${effectiveVariableName(templateName, LOCAL_PORT_VARIABLE)}=${port}`,
    `${effectiveVariableName(templateName, LOCAL_PROJECT_VARIABLE)}=${auth.projectId}`,
    '',
  ].join('\n');
}

function writeTokenFile(auth: LocalAuthContext, port?: number): void {
  ensurePrivateDirectory(dirname(auth.tokenPath));
  if (existsSync(auth.tokenPath) && lstatSync(auth.tokenPath).isSymbolicLink()) throw new Error("refusing symbolic local auth token path");
  const bytes = Buffer.from(tokenFileContent(auth, port), "utf8");
  const temporary = `${auth.tokenPath}.${process.pid}.${Date.now()}.${randomBytes(8).toString("hex")}.tmp`;
  let descriptor: number | undefined;
  try {
    descriptor = openSync(temporary, constants.O_CREAT | constants.O_EXCL | constants.O_WRONLY, 0o600);
    writeSync(descriptor, bytes, 0, bytes.length, 0);
    try { fsyncSync(descriptor); } catch (error: unknown) {
      const code = error && typeof error === "object" && "code" in error ? error.code : undefined;
      if (code !== "EINVAL" && code !== "ENOTSUP" && code !== "EPERM") throw error;
    }
    closeSync(descriptor);
    descriptor = undefined;
    if (process.platform !== "win32") chmodSync(temporary, 0o600);
    renameSync(temporary, auth.tokenPath);
  } finally {
    if (descriptor !== undefined) closeSync(descriptor);
    if (existsSync(temporary)) unlinkSync(temporary);
  }
}

export function createProjectLocalAuth(projectPath: string, relayInstanceId: string, root = join(homedir(), ".ccp", "local-auth")): LocalAuthContext {
  z.string().uuid().parse(relayInstanceId);
  const identity = projectIdentity(projectPath);
  return { ...identity, relayInstanceId, token: encodeBase64Url(randomBytes(32)),
    tokenPath: join(root, `${identity.projectId}.env`), variableName: LOCAL_TOKEN_VARIABLE };
}

export function bindLocalAuthToPort(auth: LocalAuthContext, port: number): LocalAuthBinding {
  if (!Number.isSafeInteger(port) || port < 1 || port > 65535) throw new RangeError("local auth port must be in 1..65535");
  const previousPort = auth.boundPort;
  writeTokenFile(auth, port);
  auth.boundPort = port;
  return { templateName: `ccp3x_${port}`, tokenPath: auth.tokenPath, previousPort };
}

function valueMatches(expected: string, received: unknown): boolean {
  const candidate = typeof received === "string" && received.length <= 256 ? received : "";
  const expectedDigest = createHash("sha256").update(expected, "utf8").digest();
  const candidateDigest = createHash("sha256").update(candidate, "utf8").digest();
  return timingSafeEqual(expectedDigest, candidateDigest) && candidate.length === expected.length;
}

function denial(status: number, code: ConstructorParameters<typeof CcpError>[0], error: string): LocalIngressDenial {
  return { status, body: toCcpErrorBody(new CcpError(code, error)) };
}

export function extractIdempotencyKey(request: IncomingMessage): string | undefined {
  const rawValues: string[] = [];
  for (let index = 0; index + 1 < request.rawHeaders.length; index += 2) {
    if (request.rawHeaders[index].toLowerCase() === IDEMPOTENCY_KEY_HEADER) rawValues.push(request.rawHeaders[index + 1]);
  }
  const normalized = request.headers[IDEMPOTENCY_KEY_HEADER];
  const values = rawValues.length > 0
    ? rawValues
    : Array.isArray(normalized) ? normalized : typeof normalized === "string" ? normalized.split(",").map((value) => value.trim()) : [];
  if (values.length === 0) return undefined;
  if (values.length !== 1 || values.some((value) => value !== values[0])) {
    throw new CcpError("CCP_IDEMPOTENCY_CONFLICT", "Conflicting local idempotency headers are not accepted.");
  }
  const key = values[0];
  if (Buffer.byteLength(key, "utf8") > 128) {
    throw new CcpError("CCP_LIMIT_EXCEEDED", "Local idempotency key must not exceed 128 bytes.");
  }
  if (!IdempotencyKeySchema.safeParse(key).success) {
    throw new CcpError("CCP_CANONICAL_INVALID", "Local idempotency key must be 16..128 base64url characters.");
  }
  return key;
}

export function validateLocalIngress(auth: LocalAuthContext, request: IncomingMessage, pathname = "/"): LocalIngressDenial | undefined {
  const remoteAddress = request.socket.remoteAddress;
  if (remoteAddress !== "127.0.0.1" && remoteAddress !== "::ffff:127.0.0.1") return denial(403, "CCP_AUTH_INVALID", "Local route accepts loopback clients only.");
  if (request.headers.forwarded !== undefined || request.headers["x-forwarded-for"] !== undefined || request.headers["x-real-ip"] !== undefined) return denial(400, "CCP_AUTH_INVALID", "Forwarded client identity headers are not accepted.");
  const localPort = request.socket.localPort;
  const host = request.headers.host;
  if (typeof host !== "string" || !new Set([`127.0.0.1:${localPort}`, `localhost:${localPort}`]).has(host.toLowerCase())) return denial(400, "CCP_AUTH_INVALID", "Local request Host is invalid.");
  const origin = request.headers.origin;
  if (origin !== undefined) {
    let parsedOrigin: URL;
    try { parsedOrigin = new URL(origin); } catch { return denial(403, "CCP_AUTH_INVALID", "Request Origin is invalid."); }
    if ((parsedOrigin.protocol !== "http:" && parsedOrigin.protocol !== "https:") || !["127.0.0.1", "localhost"].includes(parsedOrigin.hostname)
      || parsedOrigin.username || parsedOrigin.password || parsedOrigin.pathname !== "/" || parsedOrigin.search || parsedOrigin.hash) return denial(403, "CCP_AUTH_INVALID", "Foreign request Origin is not accepted.");
  }
  const fetchSite = request.headers["sec-fetch-site"];
  if (fetchSite !== undefined && fetchSite !== "same-origin" && fetchSite !== "none") return denial(403, "CCP_AUTH_INVALID", "Cross-site browser requests are not accepted.");
  if (request.headers["content-encoding"] !== undefined) return denial(415, "CCP_CANONICAL_INVALID", "Compressed local request bodies are not accepted.");
  if (!["GET", "POST", "PUT", "DELETE"].includes(request.method || "")) return denial(405, "CCP_AUTH_INVALID", "HTTP method is not allowed.");
  if (request.method !== "GET") {
    const contentType = String(request.headers["content-type"] ?? "").toLowerCase();
    if (contentType !== "application/json" && contentType !== "application/json; charset=utf-8") return denial(415, "CCP_CANONICAL_INVALID", "Local request requires application/json; charset=utf-8.");
  }
  // Explicit local loopback discovery exception to default-deny authentication:
  // only GET /utcp and GET /build-info are tokenless after the ingress checks above.
  // Project/session/Gateway identity at /connection remains credential-bound.
  const publicGet = request.method === "GET" && (pathname === "/utcp" || pathname === "/build-info");
  if (publicGet) return undefined;
  if (!valueMatches(auth.token, request.headers[LOCAL_TOKEN_HEADER])) return denial(401, "CCP_AUTH_REQUIRED", "Valid local API token is required.");
  if (!valueMatches(auth.relayInstanceId, request.headers[LOCAL_INSTANCE_HEADER])) return denial(401, "CCP_AUTH_INVALID", "Local API credential is bound to a different relay instance.");
  if (auth.boundPort !== undefined && !valueMatches(String(auth.boundPort), request.headers[LOCAL_PORT_HEADER])) return denial(401, "CCP_AUTH_INVALID", "Local API credential is bound to a different port.");
  if (auth.projectId && !valueMatches(auth.projectId, request.headers[LOCAL_PROJECT_HEADER])) return denial(401, "CCP_AUTH_INVALID", "Local API credential is bound to a different project.");
  return undefined;
}
